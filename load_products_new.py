def main():
    """Основная функция загрузки"""
    print("🗑️  Удаление старых товаров...")
    db.delete_all_products()
    print("✅ Старые товары удалены!\n")
    
    print("📦 Загрузка товаров с вариантами...")
    products_map = load_products()
    
    success_products = 0
    success_variants = 0
    errors = 0
    
    for key, data in products_map.items():
        category_id, brand, extra_info, volume, base_price = key
        
        # Определить имя и крепость
        if category_id in [3, 4]:  # Картриджи и поды
            name = extra_info
            strength = ''
        else:  # Жидкости и одноразки
            name = brand
            strength = extra_info
        
        try:
            # Создать основной товар
            product_id = db.add_product(
                category_id=category_id,
                name=name,
                brand=brand,
                base_price=base_price,
                strength=strength,
                volume=volume,
                cashback_rate=calculate_cashback_rate(category_id),
                is_hot=1 if data['is_hot'] else 0
            )
            
            success_products += 1
            print(f"✓ {brand} {strength} {volume}".strip())
            
            # Добавить варианты (вкусы)
            for flavor, price, qty in data['variants']:
                try:
                    db.add_product_variant(
                        product_id=product_id,
                        flavor=flavor,
                        price=price,
                        quantity=qty
                    )
                    success_variants += 1
                    print(f"  ✓ {flavor} ({qty} шт)")
                except Exception as e:
                    errors += 1
                    print(f"  ✗ Ошибка варианта {flavor}: {e}")
        
        except Exception as e:
            errors += 1
            print(f"✗ Ошибка: {brand} - {e}")
    
    print(f"\n{'='*60}")
    print(f"✅ Успешно загружено:")
    print(f"   📦 Товаров: {success_products}")
    print(f"   🎨 Вариантов: {success_variants}")
    if errors > 0:
        print(f"❌ Ошибок: {errors}")
    print(f"{'='*60}\n")
    
    # Вывести статистику по категориям
    categories = db.get_categories()
    print("📊 Статистика по категориям:")
    for cat in categories:
        print(f"  {cat['icon']} {cat['name']}: товаров - информация недоступна в новой структуре")


if __name__ == '__main__':
    main()





